type recordingRunner struct {
	calls [][]string
	err   error
}

func (r *recordingRunner) Run(_ context.Context, _ string, name string, args ...string) (execx.Result, error) {
	r.calls = append(r.calls, append([]string{name}, args...))
	return execx.Result{}, r.err
}

func TestSyncVersionsWritesWorkspaceVersionAndPins(t *testing.T) {
	root := newSyncWorkspace(t, false)
	run := &recordingRunner{}
	syncer := syncerForTest(t)
	changed, err := syncer.SyncVersions(context.Background(), run, root, nextVersions(t, root, "0.2.0"))
	if err != nil {
		t.Fatalf("SyncVersions: %v", err)
	}
	rootManifest := readFile(t, filepath.Join(root, "Cargo.toml"))
	for _, want := range []string{
		"version = \"0.2.0\"",
		`sync-core = { path = "crates/core", version = "0.2.0" }`,
	} {
		if !strings.Contains(rootManifest, want) {
			t.Fatalf("root manifest is missing %q:\n%s", want, rootManifest)
		}
	}
	cliManifest := readFile(t, filepath.Join(root, "crates", "cli", "Cargo.toml"))
	for _, want := range []string{
		`sync-core = { path = "../core", version = "0.2.0" }`,
		`version = "0.0.9"`,
	} {
		if !strings.Contains(cliManifest, want) {
			t.Fatalf("cli manifest is missing %q:\n%s", want, cliManifest)
		}
	}
	if len(run.calls) != 0 {
		t.Fatalf("cargo must not run without Cargo.lock: %v", run.calls)
	}
	for _, want := range []string{"Cargo.toml", "crates/cli/Cargo.toml"} {
		if !slices.Contains(changed, want) {
			t.Fatalf("changed = %v, want %s", changed, want)
		}
	}
}

func TestSyncVersionsAddsMissingVersion(t *testing.T) {
	root := newSyncWorkspace(t, false)
	writeManifest(t, root, "crates/cli/Cargo.toml", "[package]\nname = \"sync-cli\"\nversion.workspace = true\n\n[dependencies]\nsync-core = { path = \"../core\" }\n")
	syncer := syncerForTest(t)
	if _, err := syncer.SyncVersions(context.Background(), &recordingRunner{}, root, nextVersions(t, root, "0.2.0")); err != nil {
		t.Fatalf("SyncVersions: %v", err)
	}
	cliManifest := readFile(t, filepath.Join(root, "crates", "cli", "Cargo.toml"))
	if !strings.Contains(cliManifest, `sync-core = { path = "../core", version = "0.2.0" }`) {
		t.Fatalf("missing version was not added:\n%s", cliManifest)
	}
}

func TestSyncVersionsRefreshesLockfile(t *testing.T) {
	root := newSyncWorkspace(t, true)
	run := &recordingRunner{}
	syncer := syncerForTest(t)
	changed, err := syncer.SyncVersions(context.Background(), run, root, nextVersions(t, root, "0.2.0"))
	if err != nil {
		t.Fatalf("SyncVersions: %v", err)
	}
	if len(run.calls) != 1 || !slices.Equal(run.calls[0], []string{"cargo", "update", "--workspace"}) {
		t.Fatalf("cargo calls = %v", run.calls)
	}
	if !slices.Contains(changed, "Cargo.lock") {
		t.Fatalf("changed = %v, want Cargo.lock", changed)
	}
}

func TestSyncVersionsReportsCargoFailure(t *testing.T) {
	root := newSyncWorkspace(t, true)
	run := &recordingRunner{err: errors.New("cargo exploded")}
	syncer := syncerForTest(t)
	_, err := syncer.SyncVersions(context.Background(), run, root, nextVersions(t, root, "0.2.0"))
	if err == nil || !strings.Contains(err.Error(), "cargo update") {
		t.Fatalf("err = %v, want a cargo update error", err)
	}
}

func syncerForTest(t *testing.T) ecosystem.VersionSyncer {
	t.Helper()
	syncer, ok := rust.New().(ecosystem.VersionSyncer)
	if !ok {
		t.Fatal("rust adapter does not implement VersionSyncer")
	}
	return syncer
}

func nextVersions(t *testing.T, root, next string) []ecosystem.Package {
	t.Helper()
	pkgs, err := rust.New().Detect(root)
	if err != nil {
		t.Fatalf("Detect: %v", err)
	}
	out := make([]ecosystem.Package, 0, len(pkgs))
	for _, pkg := range pkgs {
		pkg.Version = next
		out = append(out, pkg)
	}
	return out
}

func newSyncWorkspace(t *testing.T, withLock bool) string {
	t.Helper()
	root := t.TempDir()
	writeManifest(t, root, "Cargo.toml", `[workspace]
members = ["crates/core", "crates/cli"]

[workspace.package]
version = "0.1.0"
edition = "2021"

[workspace.dependencies]
sync-core = { path = "crates/core" }
`)
	writeManifest(t, root, "crates/core/Cargo.toml", `[package]
name = "sync-core"
version.workspace = true
`)
	writeManifest(t, root, "crates/cli/Cargo.toml", `[package]
name = "sync-cli"
version.workspace = true

[dependencies]
sync-core = { path = "../core", version = "0.1.0" }

[dev-dependencies]
sync-core = { path = "../core", version = "0.0.9" }
`)
	if withLock {
		writeManifest(t, root, "Cargo.lock", "# This file is automatically @generated by Cargo.\n")
	}
	return root
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func TestSyncVersionsUsesPerPackageVersions(t *testing.T) {
	root := t.TempDir()
	writeManifest(t, root, "Cargo.toml", "[workspace]\nmembers = [\"crates/core\", \"crates/cli\"]\n")
	writeManifest(t, root, "crates/core/Cargo.toml", "[package]\nname = \"explicit-core\"\nversion = \"0.1.0\"\n")
	writeManifest(t, root, "crates/cli/Cargo.toml", `[package]
name = "explicit-cli"
version = "0.3.0"

[dependencies]
explicit-core = { path = "../core", version = "0.1.0" }
`)
	pkgs, err := rust.New().Detect(root)
	if err != nil {
		t.Fatalf("Detect: %v", err)
	}
	for i := range pkgs {
		if pkgs[i].Name == "explicit-core" {
			pkgs[i].Version = "0.2.0"
		} else {
			pkgs[i].Version = "0.4.0"
		}
	}
	changed, err := syncerForTest(t).SyncVersions(context.Background(), &recordingRunner{}, root, pkgs)
	if err != nil {
		t.Fatalf("SyncVersions: %v", err)
	}
	cliManifest := readFile(t, filepath.Join(root, "crates", "cli", "Cargo.toml"))
	if !strings.Contains(cliManifest, `explicit-core = { path = "../core", version = "0.2.0" }`) {
		t.Fatalf("the pin must follow the dependency version:\n%s", cliManifest)
	}
	if !slices.Equal(changed, []string{"crates/cli/Cargo.toml"}) {
		t.Fatalf("changed = %v, want only the dependent manifest", changed)
	}
}
