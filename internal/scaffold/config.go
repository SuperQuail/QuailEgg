package scaffold

import (
	"sort"
	"strconv"
	"strings"

	"github.com/SuperQuail/QuailEgg/internal/config"
)

func renderConfig(opts Options, packages map[string]config.Package) []byte {
	var b strings.Builder
	b.WriteString("# Generated by qegg. Keep this file in version control.\n")
	b.WriteString("schema_version = 1\n\n")
	b.WriteString("[project]\n")
	b.WriteString("default_branch = " + strconv.Quote(opts.BaseBranch) + "\n\n")
	b.WriteString("[git]\n")
	b.WriteString("tag_prefix = " + strconv.Quote(opts.TagPrefix) + "\n")
	b.WriteString("remote = " + strconv.Quote(opts.Remote) + "\n\n")
	b.WriteString("[release]\n")
	b.WriteString("mode = " + strconv.Quote(opts.Mode) + "\n")

	b.WriteString("github_release = true\n")
	b.WriteString("commit_message = " + strconv.Quote("chore(release): v{{version}}") + "\n\n")
	b.WriteString("[changes]\n")
	b.WriteString("dir = " + strconv.Quote(opts.ChangesDir) + "\n")
	b.WriteString("scope = " + stringSlice(opts.Scope) + "\n\n")
	b.WriteString("[verify]\n")
	b.WriteString("commands = " + stringSlice(opts.VerifyCommands) + "\n")
	b.WriteString("timeout = " + strconv.Quote("15m") + "\n")
	b.WriteString("fail_fast = true\n\n")
	b.WriteString("[publish]\n")
	b.WriteString("registries = " + stringSlice(opts.Registries) + "\n")

	names := make([]string, 0, len(packages))
	for name := range packages {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		pkg := packages[name]
		b.WriteString("\n[packages." + tomlKey(name) + "]\n")
		b.WriteString("path = " + strconv.Quote(pkg.Path) + "\n")
		b.WriteString("resolver = " + strconv.Quote(pkg.Resolver) + "\n")
		publish := true
		if pkg.Publish != nil {
			publish = *pkg.Publish
		}
		b.WriteString("publish = " + strconv.FormatBool(publish) + "\n")
		if len(pkg.DependsOn) > 0 {
			b.WriteString("depends-on = " + stringSlice(pkg.DependsOn) + "\n")
		}
	}
	return []byte(b.String())
}

func stringSlice(values []string) string {
	if len(values) == 0 {
		return "[]"
	}
	parts := make([]string, 0, len(values))
	for _, value := range values {
		parts = append(parts, strconv.Quote(value))
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

func tomlKey(name string) string {
	if strings.ContainsAny(name, "@/. ") || strings.Contains(name, "-") {
		return strconv.Quote(name)
	}
	return name
}

// MergePackages preserves the existing configuration and appends new package tables.
func MergePackages(existing []byte, opts Options, packages map[string]config.Package) []byte {
	text := string(existing)
	var additions strings.Builder
	names := make([]string, 0, len(packages))
	for name := range packages {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if strings.Contains(text, "[packages."+tomlKey(name)+"]") {
			continue
		}
		pkg := packages[name]
		additions.WriteString("\n[packages." + tomlKey(name) + "]\n")
		additions.WriteString("path = " + strconv.Quote(pkg.Path) + "\n")
		additions.WriteString("resolver = " + strconv.Quote(pkg.Resolver) + "\n")
		publish := true
		if pkg.Publish != nil {
			publish = *pkg.Publish
		}
		additions.WriteString("publish = " + strconv.FormatBool(publish) + "\n")
	}
	if additions.Len() == 0 {
		return existing
	}
	return []byte(strings.TrimRight(text, "\n") + "\n" + additions.String())
}
