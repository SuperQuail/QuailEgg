package scaffold

import (
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/SuperQuail/QuailEgg/internal/config"
)

func renderConfig(opts Options, packages map[string]config.Package) []byte {
	var b strings.Builder
	b.WriteString("# Generated by qegg. Keep this file in version control.\n")
	b.WriteString("schema_version = 1\n")
	if opts.Develop {
		b.WriteString("develop = true\n")
	}
	b.WriteString("\n")
	b.WriteString("[project]\n")
	b.WriteString("default_branch = " + strconv.Quote(opts.BaseBranch) + "\n")
	if opts.Repo != "" {
		b.WriteString("repo = " + strconv.Quote(opts.Repo) + "\n")
	}
	b.WriteString("\n")
	b.WriteString("[git]\n")
	b.WriteString("tag_prefix = " + strconv.Quote(opts.TagPrefix) + "\n")
	b.WriteString("remote = " + strconv.Quote(opts.Remote) + "\n\n")
	b.WriteString("[release]\n")
	b.WriteString("mode = " + strconv.Quote(opts.Mode) + "\n")

	b.WriteString("github_release = true\n")
	commitMessage := "chore(release): v{{version}}"
	if len(packages) > 1 && opts.VersionScope != config.VersionScopeShared {
		commitMessage = "chore(release): bump versions"
	}
	b.WriteString("commit_message = " + strconv.Quote(commitMessage) + "\n")
	if opts.VersionScope != "" && opts.VersionScope != config.VersionScopePackage {
		b.WriteString("version_scope = " + strconv.Quote(opts.VersionScope) + "\n")
	}
	if opts.Environment != "" {
		b.WriteString("environment = " + strconv.Quote(opts.Environment) + "\n")
	}
	b.WriteString("\n")
	b.WriteString("[changes]\n")
	b.WriteString("dir = " + strconv.Quote(opts.ChangesDir) + "\n")
	b.WriteString("scope = " + stringSlice(opts.Scope) + "\n\n")
	b.WriteString("[verify]\n")
	b.WriteString("commands = " + stringSlice(opts.VerifyCommands) + "\n")
	b.WriteString("timeout = " + strconv.Quote("15m") + "\n")
	b.WriteString("fail_fast = true\n\n")
	b.WriteString("[publish]\n")
	b.WriteString("registries = " + stringSlice(opts.Registries) + "\n")

	names := make([]string, 0, len(packages))
	for name := range packages {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		pkg := packages[name]
		b.WriteString("\n[packages." + tomlKey(name) + "]\n")
		if manifest := strings.TrimSpace(pkg.Name); manifest != "" && manifest != name {
			b.WriteString("name = " + strconv.Quote(manifest) + "\n")
		}
		b.WriteString("path = " + strconv.Quote(pkg.Path) + "\n")
		b.WriteString("resolver = " + strconv.Quote(pkg.Resolver) + "\n")
		publish := true
		if pkg.Publish != nil {
			publish = *pkg.Publish
		}
		b.WriteString("publish = " + strconv.FormatBool(publish) + "\n")
		if len(pkg.DependsOn) > 0 {
			b.WriteString("depends-on = " + stringSlice(pkg.DependsOn) + "\n")
		}
	}
	for _, file := range opts.VersionFiles {
		b.WriteString("\n[[version.file]]\n")
		b.WriteString("path = " + strconv.Quote(file.Path) + "\n")
		if file.Format != "" {
			b.WriteString("format = " + strconv.Quote(file.Format) + "\n")
		}
		if file.Key != "" {
			b.WriteString("key = " + strconv.Quote(file.Key) + "\n")
		}
	}
	return []byte(b.String())
}

func stringSlice(values []string) string {
	if len(values) == 0 {
		return "[]"
	}
	parts := make([]string, 0, len(values))
	for _, value := range values {
		parts = append(parts, strconv.Quote(value))
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

func tomlKey(name string) string {
	if strings.ContainsAny(name, "@/. ") || strings.Contains(name, "-") {
		return strconv.Quote(name)
	}
	return name
}

// MergePackages preserves the existing configuration and appends new package tables.
func MergePackages(existing []byte, opts Options, packages map[string]config.Package) []byte {
	text := string(existing)
	var additions strings.Builder
	names := make([]string, 0, len(packages))
	for name := range packages {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if strings.Contains(text, "[packages."+tomlKey(name)+"]") {
			continue
		}
		pkg := packages[name]
		additions.WriteString("\n[packages." + tomlKey(name) + "]\n")
		if manifest := strings.TrimSpace(pkg.Name); manifest != "" && manifest != name {
			additions.WriteString("name = " + strconv.Quote(manifest) + "\n")
		}
		additions.WriteString("path = " + strconv.Quote(pkg.Path) + "\n")
		additions.WriteString("resolver = " + strconv.Quote(pkg.Resolver) + "\n")
		publish := true
		if pkg.Publish != nil {
			publish = *pkg.Publish
		}
		additions.WriteString("publish = " + strconv.FormatBool(publish) + "\n")
	}
	if additions.Len() == 0 {
		return existing
	}
	return []byte(strings.TrimRight(text, "\n") + "\n" + additions.String())
}

// MergeVersionFiles appends the [[version.file]] tables an existing
// configuration does not carry yet. Callers pass only new files, so a hand
// edited configuration keeps every version file it already lists.
func MergeVersionFiles(existing []byte, files []config.VersionFile) []byte {
	if len(files) == 0 {
		return existing
	}
	var additions strings.Builder
	for _, file := range files {
		additions.WriteString("\n[[version.file]]\n")
		additions.WriteString("path = " + strconv.Quote(file.Path) + "\n")
		if file.Format != "" {
			additions.WriteString("format = " + strconv.Quote(file.Format) + "\n")
		}
		if file.Key != "" {
			additions.WriteString("key = " + strconv.Quote(file.Key) + "\n")
		}
	}
	return []byte(strings.TrimRight(string(existing), "\n") + "\n" + additions.String())
}

// developLine matches a top-level develop assignment.
var developLine = regexp.MustCompile(`^[ \t]*develop[ \t]*=`)

// MergeDevelop writes or removes the top-level develop flag in an existing
// configuration. It only touches lines before the first table, so a section key
// with the same name is never mistaken for the project setting. Passing false
// removes the flag; passing true inserts it after schema_version or replaces
// the existing value.
func MergeDevelop(existing []byte, value bool) []byte {
	if len(existing) == 0 {
		return existing
	}
	lines := strings.Split(string(existing), "\n")
	topEnd := len(lines)
	for i, line := range lines {
		if strings.HasPrefix(strings.TrimSpace(line), "[") {
			topEnd = i
			break
		}
	}
	found := -1
	for i := 0; i < topEnd; i++ {
		if developLine.MatchString(lines[i]) {
			found = i
			break
		}
	}
	if !value {
		if found < 0 {
			return existing
		}
		lines = append(lines[:found:found], lines[found+1:]...)
		// Removing a line between two blank lines would leave an empty gap.
		if found < len(lines) && strings.TrimSpace(lines[found]) == "" && found > 0 && strings.TrimSpace(lines[found-1]) == "" {
			lines = append(lines[:found:found], lines[found+1:]...)
		}
		return []byte(strings.Join(lines, "\n"))
	}
	if found >= 0 {
		lines[found] = "develop = true"
		return []byte(strings.Join(lines, "\n"))
	}
	// Keep schema_version first so a merged file reads like a rendered one.
	at := 0
	for i := 0; i < topEnd; i++ {
		if strings.HasPrefix(strings.TrimSpace(lines[i]), "schema_version") {
			at = i + 1
			break
		}
	}
	lines = append(lines[:at:at], append([]string{"develop = true"}, lines[at:]...)...)
	return []byte(strings.Join(lines, "\n"))
}

// projectRepoLine matches an existing project.repo assignment.
var projectRepoLine = regexp.MustCompile(`(?m)^[ \t]*repo[ \t]*=`)

// MergeProjectRepo records the project repository identity in an existing
// configuration when the field is missing. It never rewrites other lines, so a
// hand-adjusted config keeps every setting it had.
func MergeProjectRepo(existing []byte, repo string) []byte {
	if repo == "" || len(existing) == 0 {
		return existing
	}
	text := string(existing)
	if projectRepoLine.MatchString(text) {
		return existing
	}
	lines := strings.Split(text, "\n")
	for i, line := range lines {
		if strings.TrimSpace(line) != "[project]" {
			continue
		}
		// Keep the field after default_branch so a regenerated file reads the
		// same way a freshly rendered one does.
		at := i + 1
		for j := i + 1; j < len(lines); j++ {
			trimmed := strings.TrimSpace(lines[j])
			if strings.HasPrefix(trimmed, "[") {
				break
			}
			if strings.HasPrefix(trimmed, "default_branch") {
				at = j + 1
			}
		}
		insert := []string{"repo = " + strconv.Quote(repo)}
		merged := append(lines[:at:at], append(insert, lines[at:]...)...)
		return []byte(strings.Join(merged, "\n"))
	}
	return []byte(strings.TrimRight(text, "\n") + "\n\n[project]\nrepo = " + strconv.Quote(repo) + "\n")
}
